// ─── Fact taxonomy ───────────────────────────────────────────────────────────

export type FactType =
  | 'allergy'
  | 'medication'
  | 'diagnosis'
  | 'symptom'
  | 'vital'
  | 'anthropometric'
  | 'lab_result'
  | 'imaging_result'
  | 'pathology_result'
  | 'procedure'
  | 'prescription'
  | 'investigation_order'
  | 'clinical_note'
  | 'follow_up'
  | 'task'
  | 'consent'
  | 'family_history'
  | 'social_history';

export type FactStatus =
  | 'active'      // currently applies
  | 'resolved'    // was true, no longer applies
  | 'suspected'   // unconfirmed, needs clinician verification
  | 'confirmed'   // verified by a clinician
  | 'refuted'     // investigated and excluded
  | 'pending'     // awaiting action or result
  | 'cancelled'   // deliberately stopped
  | 'completed'   // task / order / procedure done
  | 'overdue';    // past due date, not completed

export type FactSource =
  | 'manual'                // clinician typed it
  | 'ai_extracted'          // AI extracted from narrative text
  | 'ai_suggested'          // AI suggestion, not yet accepted
  | 'intake_questionnaire'  // patient-reported at intake
  | 'lab_import'            // imported from lab / external system
  | 'derived_rule'          // generated by clinical rules engine
  | 'historic_record'       // carried forward from prior encounter
  | 'referral_letter';      // from referring clinician's letter

