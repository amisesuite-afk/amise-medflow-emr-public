// ─── Core fact entity ─────────────────────────────────────────────────────────

export interface ClinicalFact<T extends FactType = FactType> {
  id: string;
  patientId: string;
  encounterId: string | null;
  factType: T;
  value: T extends keyof FactValueMap ? FactValueMap[T] : Record<string, unknown>;
  status: FactStatus;
  version: number;           // monotonically increasing per fact
  source: FactSource;
  sourceFactIds: string[];   // facts this was derived/extracted from
  ruleId: string | null;     // rules-engine rule that created this, if any
  createdBy: string;         // user ID, 'system', or 'ai'
  createdAt: string;
  updatedAt: string;
  verifiedBy: string | null; // clinician who explicitly verified safety-critical facts
  verifiedAt: string | null;
  expiresAt: string | null;  // auto-expire time-limited facts
  displayReason: string | null; // WHY this fact appears — shown in provenance UI
  metadata: Record<string, unknown>;
}

