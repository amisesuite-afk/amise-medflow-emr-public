// ─── Rules engine ─────────────────────────────────────────────────────────────

export interface RuleAlert {
  severity: 'critical' | 'warning' | 'info';
  message: string;
  detail: string;
  requiresAcknowledgement: boolean;
  requiresOverrideReason: boolean;
  actionLabel: string | null;
}

export interface RuleOutput {
  alert?: RuleAlert;
  tasks?: Array<Partial<TaskValue> & { title: string }>;
  suggestedFacts?: Array<{
    factType: FactType;
    value: Record<string, unknown>;
    displayReason: string;
  }>;
  block?: { reason: string };
  followUps?: Array<Partial<FollowUpValue> & { reason: string; timeframe: string; dueDateIso: string }>;
}

export interface ActiveAlert {
  id: string;
  ruleId: string;
  severity: RuleAlert['severity'];
  message: string;
  detail: string;
  triggeringFactId: string;
  relatedFactIds: string[];
  requiresAcknowledgement: boolean;
  acknowledgedBy: string | null;
  acknowledgedAt: string | null;
  overrideReason: string | null;
  createdAt: string;
}

export interface ClinicalRule {
  id: string;
  name: string;
  description: string;
  category: 'safety' | 'guideline' | 'quality' | 'workflow';
  priority: 'critical' | 'high' | 'medium' | 'low';
  triggerTypes: FactType[];
  evaluate: (allFacts: ClinicalFact[], trigger: ClinicalFact) => RuleOutput | null;
}

